"""Writes tree-sitter-robot/translations.json from Robot Framework's own
translations (robot.conf.languages), for the grammar to accept localized
section headers and settings (`Language: pt-BR` and similar).

Run with a Python that has Robot Framework installed:

    python scripts/generate-translations.py

then regenerate the parser (`tree-sitter generate` in tree-sitter-robot/).

Also updates the import settings (Library, Resource, Variables and their
translations) that languages/robot/outline.scm lists in the outline.
"""

import json
import re
from pathlib import Path

from robot.conf.languages import Language
from robot.version import VERSION

HEADERS = {
    "settings": "settings_header",
    "variables": "variables_header",
    "test_cases": "test_cases_header",
    "tasks": "tasks_header",
    "keywords": "keywords_header",
    "comments": "comments_header",
}
# Settings allowed in the *** Settings *** section.
SECTION_SETTINGS = [
    "library", "resource", "variables", "name", "documentation", "metadata",
    "suite_setup", "suite_teardown", "test_setup", "task_setup", "test_teardown",
    "task_teardown", "test_template", "task_template", "test_timeout", "task_timeout",
    "test_tags", "task_tags", "keyword_tags",
]
# [Bracketed] settings of test cases / tasks and of keywords.
TEST_SETTINGS = ["documentation", "tags", "setup", "teardown", "template", "timeout"]
KEYWORD_SETTINGS = ["documentation", "tags", "arguments", "setup", "teardown", "timeout"]


def translated(attribute_names):
    """All non-English names of the given Language attributes, sorted."""
    names = set()
    for language in Language.__subclasses__():
        if language.code == "en":
            continue
        values = {getattr(language, attribute, None) for attribute in attribute_names}
        names.update(value for value in values if value)
        # Renamed terms keep working, with a deprecation warning, so files
        # written with the old name (Finnish `Testin Tagit`) still parse.
        for old, (new, _version) in getattr(language, "deprecations", {}).items():
            if new in values:
                names.add(old)
    return sorted(names)


data = {
    "_comment": f"Generated by scripts/generate-translations.py from Robot Framework {VERSION}. Do not edit.",
    "languages": sorted(language.code for language in Language.__subclasses__() if language.code != "en"),
    "headers": {key: translated([attr]) for key, attr in HEADERS.items()},
    "section_settings": translated([f"{name}_setting" for name in SECTION_SETTINGS]),
    "test_settings": translated([f"{name}_setting" for name in TEST_SETTINGS]),
    "keyword_settings": translated([f"{name}_setting" for name in KEYWORD_SETTINGS]),
}

root = Path(__file__).resolve().parent.parent
out = root / "tree-sitter-robot" / "translations.json"
out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
counts = {key: len(value) for key, value in data["headers"].items()}
print(f"wrote {out}: {len(data['languages'])} languages, headers {counts}, "
      f"{len(data['section_settings'])} section settings, {len(data['test_settings'])} test settings, "
      f"{len(data['keyword_settings'])} keyword settings")

# The outline lists imports; tree-sitter queries cannot read translations.json,
# so the names go into the query's regex.
imports = ["Library", "Resource", "Variables"] + translated(
    ["library_setting", "resource_setting", "variables_setting"]
)
outline = root / "languages" / "robot" / "outline.scm"
query = outline.read_text(encoding="utf-8")
if any(re.search(r'[\\.^$|?*+()\[\]{}"]', name) for name in imports):
    raise SystemExit("an import setting name contains a regex character; escape it")
pattern = "^(?i)(" + "|".join(imports) + ")$"
query, replaced = re.subn(
    r'(; imports: generated by scripts/generate-translations.py\n\s*\(#match\? @context ")[^\n]*(")',
    lambda m: m.group(1) + pattern + m.group(2),
    query,
)
if replaced != 1:
    raise SystemExit(f"{outline}: import pattern marker not found")
outline.write_text(query, encoding="utf-8")
print(f"wrote {outline}: {len(imports)} import setting names")
